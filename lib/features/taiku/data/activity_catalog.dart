  const TaikuActivity({
    required this.id,
    required this.stageTheme,
    required this.relatedStage,
    required this.emoji,
    required this.title,
    required this.description,
    required this.steps,
    required this.difficulty,
    this.needsParent = false,
    this.tip,
  });
}

