// ─── 難易度 ───

enum ActivityDifficulty { easy, normal, hard }

extension ActivityDifficultyLabel on ActivityDifficulty {
  String get label {
    switch (this) {
      case ActivityDifficulty.easy: return 'かんたん';
      case ActivityDifficulty.normal: return 'ふつう';
      case ActivityDifficulty.hard: return 'むずかしい';
    }
  }

  String get emoji {
    switch (this) {
      case ActivityDifficulty.easy: return '🟢';
      case ActivityDifficulty.normal: return '🟡';
      case ActivityDifficulty.hard: return '🔴';
    }
  }
}

// ─── 活動モデル ───

