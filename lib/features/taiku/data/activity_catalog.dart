  return allActivities.where((a) => a.stageTheme == theme).toList();
}

/// 難易度でフィルタリング
List<TaikuActivity> filterByDifficulty(
    List<TaikuActivity> activities, ActivityDifficulty difficulty) {
  return activities.where((a) => a.difficulty == difficulty).toList();
}
