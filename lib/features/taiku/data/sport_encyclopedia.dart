/// カテゴリでフィルタ（'すべて'なら全件返す）
List<SportEntry> getSportsByCategory(String category) {
  if (category == 'すべて') return allSports;
  return allSports.where((s) => s.category == category).toList();
}

/// 人気度の星文字列を返す
String popularityStars(int score) {
  return '★' * score + '☆' * (5 - score);
}

/// 始めやすさの色コード（カテゴリバッジ用）
String beginnerColor(String level) {
  switch (level) {
    case 'かんたん':
      return '#4CAF50'; // green
    case 'ふつう':
      return '#FF9800'; // orange
    case 'むずかしい':
      return '#F44336'; // red
    default:
      return '#9E9E9E';
  }
}
